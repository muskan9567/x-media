import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
const base = process.env.X_MEDIA_TEST_URL || 'http://127.0.0.1:3000';
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, reducedMotion: 'reduce' });
const page = await context.newPage();
page.setDefaultTimeout(20000);
const errors = []; page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(base + '/posts?user=karpathy');
  await page.locator('article').first().waitFor();
  const view = await fetch(base + '/api/posts?username=karpathy').then(r => r.json());
  await page.getByRole('button', { name: 'Filters', exact: true }).click();
  assert.equal(await page.getByRole('checkbox', { name: 'Include replies', exact: true }).count(), 0);
  if (await page.getByRole('button', { name: /Show 30 more/ }).count()) await page.getByRole('button', { name: /Show 30 more/ }).click();
  const photoPost = view.posts.find(post => post.media.some(media => media.type === 'photo'));
  if (photoPost) {
    const photo = page.locator(`article[data-post-id="${photoPost.id}"] .posts-media img`).first();
    await photo.scrollIntoViewIfNeeded();
    await page.waitForFunction(id => { const img = document.querySelector(`article[data-post-id="${id}"] .posts-media img`); return img?.complete && img.naturalWidth > 0; }, photoPost.id);
    console.log('PASS live attached image renders from X CDN');
  } else console.log('SKIP live photo playback: no original photo post in this saved sample');
  const video = page.locator('article video').first();
  await video.scrollIntoViewIfNeeded();
  await video.evaluate(element => { element.preload = 'metadata'; element.load(); });
  await page.waitForFunction(() => { const video = document.querySelector('article video'); return video?.readyState >= 1 && video.duration > 0; });
  await video.evaluate(async element => { element.muted = true; await element.play(); });
  await page.waitForFunction(() => document.querySelector('article video')?.currentTime > 0.2);
  await video.evaluate(element => { element.pause(); element.currentTime = Math.min(5, element.duration / 2); });
  await page.waitForFunction(() => { const video = document.querySelector('article video'); return video && !video.seeking && video.currentTime > 1; });
  await video.screenshot({ path: '.impeccable/review/posts/video-playback.png' });
  console.log('PASS live attached video plays and seeks through local stream');
  await page.route('**/api/posts/video?**', route => route.fulfill({ status: 502, contentType: 'application/json', body: '{"error":"Video unavailable"}' }));
  await video.evaluate(element => element.load());
  await page.getByText('Video could not load.', { exact: true }).waitFor();
  assert.ok(await page.getByRole('link', { name: 'Watch on X', exact: true }).isVisible());
  await page.screenshot({ path: '.impeccable/review/posts/video-error.png' });
  await page.unroute('**/api/posts/video?**');
  await page.getByRole('button', { name: 'Try again', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('article video')?.readyState >= 1);
  await page.getByText('Video could not load.', { exact: true }).waitFor({ state: 'hidden' });
  console.log('PASS failed video offers fallback and retries successfully');
  assert.ok(await page.locator('article').first().getByRole('link', { name: /Open tweet/ }).count());
  await page.route('**/api/posts?username=karpathy', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"error":"Temporary test connection interruption"}' }));
  await page.getByRole('alert').filter({ hasText: 'Temporary test connection interruption' }).waitFor();
  assert.ok(await page.locator('article').count());
  await page.unroute('**/api/posts?username=karpathy');
  await page.getByRole('alert').filter({ hasText: 'Temporary test connection interruption' }).waitFor({ state: 'hidden' });
  console.log('PASS connection interruption retains results and recovers automatically');
  await page.getByRole('textbox', { name: 'X username or profile link' }).fill('zz_926739204k');
  await page.getByRole('button', { name: 'Find tweets', exact: true }).click();
  await page.getByRole('heading', { name: 'This account is unavailable', exact: true }).waitFor({ timeout: 45000 });
  assert.equal(await page.locator('article').count(), 0);
  await page.getByRole('navigation', { name: 'Saved tweet accounts' }).getByRole('button', { name: /^@karpathy\b/ }).click();
  await page.locator('article').first().waitFor();
  assert.ok((await page.locator('article').first().innerText()).includes('@karpathy'));
  console.log('PASS unavailable account and return to saved tweets');
  const current = await fetch(base + '/api/posts?username=karpathy').then(r => r.json());
  assert.equal(current.posts.length, view.posts.length);
  assert.deepEqual(errors, []);
} finally { await browser.close(); }
